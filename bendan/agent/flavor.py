DEFAULT_FLAVOR = LEVEL_FLAVOR[4]      # 今日挑戰、隨機關卡


def level_flavor(game):
    """這一關的提示詞池強度：關卡設定 `flavor` 優先，沒有就看關卡編號。"""
    base = LEVEL_FLAVOR.get(game.level_id, DEFAULT_FLAVOR) if isinstance(game.level_id, int) else DEFAULT_FLAVOR
    return dict(base, **(game.cfg.get("flavor") or {}))


def pick_flavor(game, rng, mood=None):
    """抽這一句要塞進 Prompt 的段落。回傳 (文字, 紀錄)。心情不好時搗蛋念頭機率 ×1.5、心情好 ×0.5。"""
    f = level_flavor(game)
    k = {"開心": 0.5, "不爽": 1.5, "鬧彆扭": 1.5}.get(getattr(mood, "name", ""), 1.0)
    picked = {"mood": rng.sample(MOODLETS, min(f["mood"], len(MOODLETS))), "habit": [], "chaos": []}
    if rng.random() < f["habit_p"]:
        picked["habit"] = rng.sample(HABITS, f["habits"])
    if rng.random() < min(0.9, f["chaos_p"] * k):
        picked["chaos"] = rng.sample(CHAOS, f["chaos"])
    lines = picked["mood"] + picked["habit"] + picked["chaos"]
    text = "\n".join(f"- {s}" for s in lines)
    if picked["habit"] or picked["chaos"]:
        text += "\n（這些是你今天的個性，請自然地演出來，也讓它影響你的 actions；但主人說「停」或「回充」時一定照做。）"
    return text, picked
